-- ===================================================================
-- WirePlumber オーディオ出力優先度設定 (HDMI最優先仕様)
-- ===================================================================
-- 【仕様】
-- ・HDMI (AD104等) の優先度を「1100」に引き上げ、起動時に自動選択（1位）させます。
-- ・内部デジタル/アナログオーディオ等のその他は「500」に下げて2位に落とします。
--
-- 【📝 今後デバイスを追加・変更したい場合のメモ】
-- 1. ターミナルで `wpctl status` を叩き、対象の `Sinks` からデバイス名を確認する
-- 2. 下記の `monitor.alsa.rules` 配列の中に、新しいテーブルブロック（{}）を追加する
-- 3. `{ "node.name", "matches", "ここにwpctl等で確認した名前（部分一致の*指定可）" }` を書く
-- 4. 優先度を上げたいなら `1100` 以上、下げたいなら `500` 以下を `priority.session` に設定する
-- ===================================================================

monitor.alsa.rules = {
  -- 👑 1位: HDMI出力（AD104などのグラフィックボード経由）
  {
    matches = {
      {
        { "node.name", "matches", "alsa_output.*hdmi*" },
      },
    },
    apply_properties = {
      ["priority.session"] = 1100, -- 最優先に引き上げ
    },
  },

  -- 🥈 2位: 内部オーディオ（デジタルステレオ / IEC958）
  {
    matches = {
      {
        { "node.name", "matches", "alsa_output.*iec958*" },
      },
    },
    apply_properties = {
      ["priority.session"] = 500,  -- 優先度を下げる
    },
  },

  -- 🥈 2位: 内部オーディオ（アナログステレオ等、その他の一般的なALSA出力）
  {
    matches = {
      {
        { "node.name", "matches", "alsa_output.*analog-stereo*" },
      },
    },
    apply_properties = {
      ["priority.session"] = 500,  -- 優先度を下げる
    },
  },
}
